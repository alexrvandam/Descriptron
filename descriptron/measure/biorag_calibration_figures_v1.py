def _nested_point(txt):
    """'19/29 caught, 2/29 false' -> (detection %, false alarm %) or None."""
    import re
    m = re.findall(r"(\d+)\s*/\s*(\d+)", str(txt or ""))
    if len(m) < 2:
        return None
    (c, n1), (f, n2) = m[0], m[1]
    return 100 * int(c) / max(1, int(n1)), 100 * int(f) / max(1, int(n2))


def panel_tradeoff(ax, cal, sweep, matrix_sweep=None):
    """Detection against false alarms, the way a diagnostic test is judged. Points on the
    diagonal carry no information: they flag described and undescribed species alike."""
    ax.plot([0, 100], [0, 100], color="#bdbdbd", lw=0.9, ls="--", zorder=1)
    ax.text(72, 76, "no information", fontsize=6.2, color="#9e9e9e", rotation=38)
    nov = cal.get("instruments", {}).get("novelty", {})
    if matrix_sweep is not None and len(matrix_sweep):
        # upper envelope over rules and thresholds: the most species caught at each false-alarm count
        g = matrix_sweep.groupby("false_alarms")["caught"].max().cummax().reset_index()
        n_u, n_d = matrix_sweep["of_unseen"].iloc[0], matrix_sweep["of_described"].iloc[0]
        ax.step(100 * g["false_alarms"] / n_d, 100 * g["caught"] / n_u, where="post", color="#212121",
                lw=1.8, zorder=4, label="character matrix (every threshold and rule)")
    for name, colour, at in (("character_matrix", "#212121", (2, 89)), ("key", "#d84315", (44, 17))):
        pt = _nested_point(nov.get(name, {}).get("nested_point"))
        if pt:
            ax.scatter([pt[1]], [pt[0]], marker="*", s=130, color=colour, edgecolor="white", lw=0.6, zorder=6)
            ax.annotate(f"{name.replace('_', ' ')}, threshold chosen\nwithout the species tested: "
                        f"{nov[name]['nested_point']}", (pt[1], pt[0]), textcoords="data",
                        xytext=at, fontsize=6.0, color=colour,
                        arrowprops=dict(arrowstyle="-", color=colour, lw=0.6))
    if sweep is not None and len(sweep):
        for rule, g in sweep.groupby("rule"):
            g = g.sort_values("widening_k")
            ax.plot(100 * g["false_alarm"], 100 * g["detection"], marker="o", ms=2.6, lw=1.0,
                    alpha=0.85, label=rule.replace(", in one specimen", ""))
        b = sweep.sort_values(["margin", "detection"], ascending=False).iloc[0]
        ax.scatter([100 * b["false_alarm"]], [100 * b["detection"]], s=120, facecolor="none",
                   edgecolor="#d84315", lw=1.6, zorder=5)
        ax.annotate(f"best here: {b['caught']}/{b['of_unseen']} caught,\n"
                    f"{b['false_alarms']}/{b['of_described']} false alarms",
                    (100 * b["false_alarm"], 100 * b["detection"]),
                    textcoords="offset points", xytext=(8, -22), fontsize=6.4, color="#d84315")
    ax.set_xlim(-2, 102)
    ax.set_ylim(-2, 102)
    ax.set_xlabel("described species wrongly flagged as new (%)", fontsize=7.4)
    ax.set_ylabel("unseen species recognised (%)", fontsize=7.4)
    ax.set_title(("Can the key or the matrix tell you a species is NEW?\n"
                  "(thin lines = key rules swept outwards; stars = honest estimates)"
                  if nov else
                  "Can the key tell you a species is NEW?\n"
                  "(each line = one rule, swept from the raw range outwards)"),
                 fontsize=8.4, loc="left")
    ax.legend(fontsize=5.8, frameon=False, loc="lower right")
    ax.tick_params(labelsize=7)
    for sp in ("top", "right"):
        ax.spines[sp].set_visible(False)


