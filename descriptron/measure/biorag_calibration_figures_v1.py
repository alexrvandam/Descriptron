def main():
    ap = argparse.ArgumentParser(description="One-page summaries of the calibration")
    ap.add_argument("--calibration", required=True, help="directory written by biorag_calibrate_v1.py")
    ap.add_argument("--key_tree", required=True)
    ap.add_argument("--reliability", default=None, help="character_reliability.tsv")
    ap.add_argument("--couplet_support", default=None,
                    help="key_couplet_support.tsv from biorag_key_jackknife_support_v1.py; default: "
                         "<calibration>/../key_jackknife_support/, when present")
    ap.add_argument("--key_support", default=None,
                    help="key_character_support.tsv from biorag_graph_support_figure_v1.py (hold-out routing "
                         "support per key character); default: <calibration>/../graph_support/, when present")
    ap.add_argument("--out_dir", default=None)
    a = ap.parse_args()

    cald = Path(a.calibration)
    out = Path(a.out_dir) if a.out_dir else cald
    out.mkdir(parents=True, exist_ok=True)
    cal = json.loads((cald / "calibration.json").read_text())
    tree = json.loads(Path(a.key_tree).read_text())
    per_species = {}
    ps = cald / "per_species.tsv"
    if ps.exists():
        t = pd.read_csv(ps, sep="\t")
        per_species = {r["species"]: {"accuracy": r.get("loo_accuracy"), "n": int(r.get("n", 0))}
                       for _, r in t.iterrows()}
    rel = None
    if a.reliability and Path(a.reliability).exists():
        rel = pd.read_csv(a.reliability, sep="\t")

    # ── sheet 1: the key with its support values ─────────────────────────────
    sweep = None
    sp_f = cald / "novelty_tradeoff.tsv"
    if sp_f.exists():
        sweep = pd.read_csv(sp_f, sep="\t")
    fig = plt.figure(figsize=(17.0, 10.6))
    gs = fig.add_gridspec(4, 3, width_ratios=[1.18, 0.92, 0.92], height_ratios=[1, 1, 1, 1],
                          hspace=0.62, wspace=0.28, left=0.035, right=0.985, top=0.9, bottom=0.055)
    cs_f = Path(a.couplet_support) if a.couplet_support else cald.parent / "key_jackknife_support" / "key_couplet_support.tsv"
    couplet_support = None
    if cs_f.exists():
        cs = pd.read_csv(cs_f, sep="\t")
        couplet_support = {int(r.couplet): (float(r.recovered), float(r.routing_support) if r.routing_support == r.routing_support
                                            else float("nan"), int(r.withheld_specimens_routed)) for r in cs.itertuples()}
    draw_key(fig.add_subplot(gs[:, 0]), tree, per_species, couplet_support)
    panel_by_size(fig.add_subplot(gs[0, 1]), cal)
    panel_diagnostic(fig.add_subplot(gs[0, 2]), cal)
    msw_f = cald / "matrix_tradeoff.tsv"
    msw = pd.read_csv(msw_f, sep="\t") if msw_f.exists() else None
    panel_tradeoff(fig.add_subplot(gs[1:3, 1]), cal, sweep, msw)
    panel_rules(fig.add_subplot(gs[1:3, 2]), cal)
    panel_summary(fig.add_subplot(gs[3, 1:]), cal)
    rs = cal.get("reference_set", {})
    # "everything below" told the reader to look at a position and shouted in
    # capitals; state the claim instead, which is what a caption has to carry
    fig.suptitle(f"Key report — {rs.get('species')} species, {rs.get('specimens')} specimens"
                 f"     |     every cutoff shown was measured on this reference set, "
                 f"not inherited from another study",
                 fontsize=11, x=0.035, ha="left", color="#1a237e")
    f1 = out / "fig_key_report.png"
    fig.savefig(f1, dpi=200)
    fig.savefig(f1.with_suffix(".pdf"))
    plt.close(fig)

    # ── sheet 2: the characters ──────────────────────────────────────────────
    fig = plt.figure(figsize=(14.5, 9.0))
    gs = fig.add_gridspec(2, 2, height_ratios=[1.5, 1], hspace=0.36, wspace=0.28,
                          left=0.17, right=0.98, top=0.88, bottom=0.07)
    sup_f = Path(a.key_support) if a.key_support else cald.parent / "graph_support" / "key_character_support.tsv"
    if sup_f.exists():
        panel_key_support(fig.add_subplot(gs[0, 0]), pd.read_csv(sup_f, sep="\t"))
    else:
        panel_key_characters(fig.add_subplot(gs[0, 0]), tree)
    panel_reliability(fig.add_subplot(gs[0, 1]), rel)
    panel_families(fig.add_subplot(gs[1, 0]), tree)
    panel_reliability_table(fig.add_subplot(gs[1, 1]), rel, cal)
    fig.suptitle("Character report — what the key rests on, and which descriptive categorical characters "
                 "repeated when read again", fontsize=11, x=0.035, ha="left", color="#1a237e")
    f2 = out / "fig_character_report.png"
    fig.savefig(f2, dpi=200)
    fig.savefig(f2.with_suffix(".pdf"))
    plt.close(fig)

    print(f"-> {f1}\n-> {f2}")


if __name__ == "__main__":
    main()
