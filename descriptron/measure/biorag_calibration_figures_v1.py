# the key as a tree
# ══════════════════════════════════════════════════════════════════════════════
def ladder(tree):
    """Walk the key and return terminals in reading order with their depth, plus the
    couplet that produced each one. A dichotomous key is a rooted binary tree; this
    lays it out the way a phylogeny is laid out, deepest path running down the page."""
    by_no = {c["number"]: c for c in tree["couplets"]}
    terminals, nodes = [], []
    seen = set()

    def walk(n, depth):
        if n in seen or n not in by_no:
            return
        seen.add(n)
        c = by_no[n]
        ch = (c.get("characters") or [{}])[0]
        nodes.append({"number": n, "depth": depth, "label": ch.get("label", "—"),
                      "threshold": ch.get("threshold"), "unit": ch.get("unit", ""),
                      "perfect": bool(ch.get("perfect_separation")),
                      "accuracy": ch.get("balanced_accuracy")})
        for side in ("A", "B"):
            g = c.get(f"{side}_goto")
            if isinstance(g, int):
                walk(g, depth + 1)
            elif g:
                terminals.append({"species": g, "depth": depth + 1, "from": n, "side": side})
    walk(tree["couplets"][0]["number"], 0)
    return nodes, terminals


def draw_key(ax, tree, per_species, support=None):
    nodes, terminals = ladder(tree)
    if not terminals:
        ax.axis("off")
        return
    y = {t["species"]: i for i, t in enumerate(sorted(
        terminals, key=lambda t: (t["depth"], t["species"])))}
    maxd = max(t["depth"] for t in terminals) or 1
    node_y = {}
    for n in sorted({t["from"] for t in terminals}):
        kids = [y[t["species"]] for t in terminals if t["from"] == n]
        node_y[n] = float(np.mean(kids)) if kids else 0.0
    depth_of = {n["number"]: n["depth"] for n in nodes}

    for t in terminals:                                  # branch to each terminal
        x0 = depth_of.get(t["from"], 0)
        yy = y[t["species"]]
        a = per_species.get(t["species"], {}).get("accuracy")
        ax.plot([x0, maxd + 0.15], [node_y.get(t["from"], yy), yy],
                color="#607d8b", lw=0.9, zorder=1, solid_capstyle="round")
        n_sp = per_species.get(t["species"], {}).get("n", 0)
        ax.scatter([maxd + 0.15], [yy], s=42, color=acc_colour(a), zorder=3,
                   edgecolor="white", linewidth=0.6)
        txt = f"  {t['species']}"
        if a is not None and not (isinstance(a, float) and np.isnan(a)):
            txt += f"   {100 * a:.0f}%  (n={n_sp})"
        else:
            txt += f"   —  (n={n_sp})"
        ax.text(maxd + 0.28, yy, txt, va="center", fontsize=7.4,
                color="#212121" if n_sp >= 3 else "#8d6e63")

    last_lab = [-99.0]
    used = {}                                            # couplets drawn on one spot: stack their support labels
    for n in nodes:                                      # the couplet characters
        if n["number"] not in node_y:
            continue
        ax.scatter([n["depth"]], [node_y[n["number"]]], marker="s", s=14,
                   color="#37474f" if n["perfect"] else "#90a4ae", zorder=3)
        sv = (support or {}).get(n["number"])
        if sv is not None:                               # jackknife support, as on a phylogeny's nodes
            rec, rout, nr = sv
            txt = f"{100 * rec:.0f}" + (f" · {100 * rout:.0f}" if rout == rout and nr >= 3 else " · –")
            spot = (n["depth"], round(node_y[n["number"]], 1))
            k = used.get(spot, 0)
            used[spot] = k + 1
            dy = -0.42 - 0.40 * k if k % 2 == 0 else 0.46 + 0.40 * (k - 1)
            ax.text(n["depth"] + 0.07, node_y[n["number"]] + dy, f"{n['number']}: " + txt, fontsize=4.9, ha="left", va="center",
                    color="#b71c1c" if (rout == rout and nr >= 5 and rout < 0.75) else "#1a237e", zorder=4)
        if n["perfect"] and abs(node_y[n["number"]] - last_lab[0]) > 1.6:
            ax.text(n["depth"] - 0.14, node_y[n["number"]], n["label"][:22], fontsize=5.2,
                    ha="right", va="center", color="#546e7a")
            last_lab[0] = node_y[n["number"]]

    ax.set_xlim(-0.6, maxd + 3.4)
    ax.set_ylim(-1.5, len(y) + 0.5)
    ax.invert_yaxis()
    ax.axis("off")
    ax.set_title("The key, and how often it reaches each species\n"
                 "terminal colour = leave-one-specimen-out accuracy; squares = couplets "
                 "(dark = perfect separation)"
                 + ("\nat each couplet, its number, then the delete-one jackknife: % of rebuilt keys that contain it ·\n"
                    "% of withheld specimens it sent the right way (red below 75%; – fewer than 3 specimens)" if support else ""),
                 fontsize=8.6 if not support else 7.8, loc="left", color="#263238")
    for c, lab in ((GOOD, "≥ 75%"), (FAIR, "50–74%"), (POOR, "< 50%"), (GREY, "not testable")):
        ax.scatter([], [], color=c, s=42, label=lab)
    ax.legend(loc="upper center", bbox_to_anchor=(0.5, -0.01), fontsize=6.3, frameon=False,
              ncol=4, title="specimens reaching the right species", title_fontsize=6.3)


