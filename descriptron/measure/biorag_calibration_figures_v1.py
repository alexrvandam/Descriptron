def panel_reliability(ax, rel: pd.DataFrame):
    if rel is None or not len(rel):
        ax.axis("off")
        ax.set_title("Descriptive characters: not measured\n"
                     "(run descriptive_states + char_reliability)", fontsize=8.4, loc="left",
                     color=GREY)
        return
    d = rel.sort_values("repeat_exact", ascending=True)
    yy = np.arange(len(d))
    cmap = {"use": GOOD, "use coarse": FAIR, "use_coarse": FAIR, "flag": POOR}
    col = [cmap.get(str(v), GREY) for v in d["verdict"]]
    ax.barh(yy, 100 * d["repeat_exact"], height=0.62, color=col, label="_")
    cz = pd.to_numeric(d.get("repeat_coarse"), errors="coerce")
    ok = cz.notna().values
    ax.scatter(100 * cz[ok], yy[ok], marker="D", s=17, color="#263238", zorder=3,
               label="after merging into bands")
    ax.axvline(80, color="#455a64", lw=0.8, ls="--")
    ax.set_yticks(yy)
    ax.set_yticklabels(d["character"], fontsize=6.6)
    ax.set_xlim(0, 104)
    ax.set_xlabel("same image, same word twice (%)", fontsize=7.4)
    ax.set_title("Descriptive words: can the scorer reproduce itself?\n"
                 "green = use as scored, amber = use as bands, red = set aside here",
                 fontsize=8.4, loc="left")
    ax.legend(fontsize=6.3, frameon=False, loc="lower right")
    ax.tick_params(labelsize=7)
    for s in ("top", "right"):
        ax.spines[s].set_visible(False)


def panel_reliability_table(ax, rel: pd.DataFrame, cal):
    ax.axis("off")
    ax.text(0.0, 0.97, "Verdicts carried into the key and the text", fontsize=9,
            weight="bold", color="#263238", transform=ax.transAxes)
    y = 0.86
    groups = [("use as scored", "use", GOOD),
              ("use only as coarse bands", "use_coarse", FAIR),
              ("set aside — not reproducible on these images", "flag", POOR)]
    dc = cal.get("descriptive_characters", {}) if isinstance(cal.get("descriptive_characters"), dict) else {}
    keymap = {"use": "use", "use_coarse": "use_coarse", "flag": "set_aside"}
    for title, k, c in groups:
        names = dc.get(keymap[k]) or []
        if not names and rel is not None and len(rel):
            names = sorted(rel[rel["verdict"].astype(str).str.replace(" ", "_") == k]["character"])
        ax.text(0.0, y, title, fontsize=7.2, weight="bold", color=c, transform=ax.transAxes)
        y -= 0.062
        for line in _wrap(", ".join(names) if names else "none", 58):
            ax.text(0.02, y, line, fontsize=6.9, color="#263238", transform=ax.transAxes)
            y -= 0.055
        y -= 0.025
    y -= 0.02
    ax.text(0.0, y, "Why this matters", fontsize=7.2, weight="bold", color="#455a64",
            transform=ax.transAxes)
    y -= 0.062
    for line in _wrap("A character the scorer cannot reproduce cannot help anyone identify a "
                      "specimen, and stating it in a description spreads the noise further. Set-aside "
                      "characters are kept out of the key and removed from the treatments. Which "
                      "characters survive is a property of this group and these images, not of the "
                      "method — expect a different list in another taxon.", 62):
        ax.text(0.02, y, line, fontsize=6.7, color="#37474f", transform=ax.transAxes)
        y -= 0.055


